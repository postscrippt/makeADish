// Turns checked recipe drafts into SQL for the Supabase SQL editor. Re-runnable: a dish is found by its source and
// Thai title and updated in place, so its id (and anyone's history or favorites pointing at it) is kept.
// Run after the migrations, supabase/seed/ingredients.sql and supabase/seed/ingredient-allergens.sql.
import type { DerivedDraft } from "./recipeBatch.ts";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

function dishSql(source: string, d: DerivedDraft): string {
  const allergens = d.allergens ?? [];
  return [
    `-- ${d.slug}`,
    "do $$",
    "declare rid int;",
    "begin",
    `  select id into rid from recipes where source = ${lit(source)} and title_th = ${lit(d.th)};`,
    "  if rid is null then",
    "    insert into recipes (title_th, description, category, spice_level, base_servings, cook_minutes, steps, source, source_license, is_thai_curated, allergen_status)",
    `    values (${lit(d.th)}, ${lit(d.description)}, ${lit(d.category)}, ${d.spice}, ${d.servings}, ${d.minutes}, ${lit(JSON.stringify(d.steps))}::jsonb, ${lit(source)}, 'MIT', true, 'tagged')`,
    "    returning id into rid;",
    "  else",
    `    update recipes set description = ${lit(d.description)}, category = ${lit(d.category)}, spice_level = ${d.spice}, base_servings = ${d.servings},`,
    `      cook_minutes = ${d.minutes}, steps = ${lit(JSON.stringify(d.steps))}::jsonb, source_license = 'MIT', is_thai_curated = true, allergen_status = 'tagged'`,
    "    where id = rid;",
    "  end if;",
    "",
    "  delete from recipe_ingredients where recipe_id = rid;",
    "  insert into recipe_ingredients (recipe_id, ingredient_id, quantity_text)",
    "  select rid, i.id, v.qty from (values",
    d.ingredients.map((i) => `    (${lit(i.slug)}, ${lit(i.qty)})`).join(",\n"),
    "  ) as v(slug, qty) join ingredients i on i.slug = v.slug;",
    "",
    "  delete from recipe_allergens where recipe_id = rid;",
    ...(allergens.length
      ? ["  insert into recipe_allergens (recipe_id, allergen_id) values", allergens.map((a) => `    (rid, ${lit(a)})`).join(",\n") + ";"]
      : ["  -- no allergens"]),
    "end $$;",
  ].join("\n");
}

export function buildRecipeSql(source: string, drafts: DerivedDraft[], batchFile: string): string {
  return [
    `-- GENERATED by scripts/build-recipes-sql.mjs from ${batchFile}. Do not edit by hand.`,
    "-- Run in the Supabase SQL editor after the migrations and the two ingredient seed files. Safe to re-run.",
    "-- If an ingredient id is missing from the ingredients table, that dish's ingredient row is silently skipped by the join,",
    "-- so check the counts after running (see docs/schema.md).",
    "",
    "begin;",
    "",
    drafts.map((d) => dishSql(source, d)).join("\n\n"),
    "",
    "commit;",
    "",
  ].join("\n");
}
