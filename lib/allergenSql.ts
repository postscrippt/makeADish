// Turns the allergen rules into SQL for the Supabase SQL editor: ingredient_allergens rows plus ingredients.allergen_status.
// Re-runnable: it first clears the rows of every tagged ingredient, then writes them again, so edits to the rules
// (including removing an allergen) are reflected. Run after supabase/seed/ingredients.sql.
import { ALLERGEN_IDS, type AllergenId } from "../data/allergen-rules.ts";
import type { AllergenRules } from "./allergens.ts";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const list = (items: string[]) => items.map(lit).join(", ");

export function buildAllergenSql(rules: AllergenRules): string {
  const slugs = Object.keys(rules).sort();
  const tagged = slugs.filter((s) => rules[s] !== null);
  const unknown = slugs.filter((s) => rules[s] === null);
  const pairs: [string, AllergenId][] = tagged.flatMap((s) => (rules[s] as AllergenId[]).map((a) => [s, a] as [string, AllergenId]));
  for (const [, a] of pairs) if (!ALLERGEN_IDS.includes(a)) throw new Error(`unknown allergen id ${a}`);

  return [
    "-- GENERATED by scripts/build-allergen-sql.mjs from data/allergen-rules.ts. Do not edit by hand.",
    "-- Run in the Supabase SQL editor after the migrations and supabase/seed/ingredients.sql. Safe to re-run.",
    "",
    "begin;",
    "",
    "-- Start clean for every ingredient we tag, so removed allergens disappear too.",
    `delete from ingredient_allergens where ingredient_id in (select id from ingredients where slug in (${list(tagged)}));`,
    "",
    pairs.length === 0
      ? "-- (no allergen rows)"
      : [
          "insert into ingredient_allergens (ingredient_id, allergen_id)",
          "select i.id, v.allergen_id",
          "from (values",
          pairs.map(([s, a]) => `  (${lit(s)}, ${lit(a)})`).join(",\n"),
          ") as v(slug, allergen_id)",
          "join ingredients i on i.slug = v.slug",
          "on conflict do nothing;",
        ].join("\n"),
    "",
    "-- Tagged means its allergens (possibly none) are recorded. Unknown means nobody has decided: never shown.",
    `update ingredients set allergen_status = 'tagged' where slug in (${list(tagged)});`,
    `update ingredients set allergen_status = 'unknown' where slug in (${list(unknown)});`,
    `delete from ingredient_allergens where ingredient_id in (select id from ingredients where slug in (${list(unknown)}));`,
    "",
    "commit;",
    "",
  ].join("\n");
}
