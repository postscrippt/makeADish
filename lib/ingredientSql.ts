// Turns the canonical ingredient list into SQL for the Supabase SQL editor (no keys or scripts to run against the database).
// Safe to run again: existing rows are updated by slug. `allergen_status` is left alone; allergens are tagged in issue #21.
import type { IngredientEntry } from "../data/ingredients.ts";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const textArray = (list: string[]) => (list.length === 0 ? "'{}'::text[]" : `ARRAY[${list.map(lit).join(", ")}]::text[]`);

export function buildIngredientsSql(entries: IngredientEntry[]): string {
  const rows = entries.map((e) => `  (${lit(e.slug)}, ${lit(e.th)}, ${lit(e.en)}, ${textArray(e.aliases)}, ${lit(e.category)})`);
  return [
    "-- GENERATED by scripts/build-ingredients-sql.mjs from data/ingredients.ts. Do not edit by hand.",
    "-- Run in the Supabase SQL editor after the migrations. Re-running updates existing rows.",
    "",
    "insert into ingredients (slug, name_th, name_en, aliases, category) values",
    rows.join(",\n"),
    "on conflict (slug) do update set",
    "  name_th  = excluded.name_th,",
    "  name_en  = excluded.name_en,",
    "  aliases  = excluded.aliases,",
    "  category = excluded.category;",
    "",
  ].join("\n");
}
